export const logOutUser = (navigate) => async (dispatch) => {
    try {
        await api.post("/auth/signout");
    } catch (error) {
        // Clear the local session even if the server is unavailable.
        console.error("Sign-out request failed", error);
    } finally {
        dispatch({ type: "LOG_OUT" });
        localStorage.removeItem("auth");
        localStorage.removeItem("CHECKOUT_ADDRESS");
        localStorage.removeItem("cartItems");
        dispatch({ type: "CLEAR_CART" });
        navigate("/login");
    }
};

export const addUpdateUserAddress =
     (sendData, toast, addressId, setOpenAddressModal) => async (dispatch) => {
    dispatch({ type: "BUTTON_LOADER" });
    try {
        if (!addressId) {
            await api.post("/addresses", sendData);
        } else {
            await api.put("/addresses/" + addressId, sendData);
        }
        await dispatch(getUserAddresses());
        toast.success("Address saved successfully");
        dispatch({ type: "IS_SUCCESS" });
        setOpenAddressModal(false);
    } catch (error) {
        console.log(error);
        const responseData = error?.response?.data;
        const fieldErrors = responseData && typeof responseData === "object"
            ? Object.entries(responseData)
                .filter(([, message]) => typeof message === "string")
                .map(([field, message]) => field + ": " + message)
                .join("; ")
            : "";
        toast.error(responseData?.message || fieldErrors || "Could not save address. Please review the fields and try again.");
        dispatch({ type: "IS_ERROR", payload: fieldErrors || responseData?.message || null });
    }
};

