export const addToCart = (data, qty = 1, toast) => 
    (dispatch, getState) => {
        // Find the product
        const products = getState().products.products || [];
        const getProduct = products.find(
            (item) => item.productId === data.productId
        );

        // Check for stocks
        const availableQuantity = getProduct?.quantity ?? data?.quantity;
        const isQuantityExist = availableQuantity != null && Number(availableQuantity) >= qty;

        // If in stock -> add
        if (isQuantityExist) {
            dispatch({ type: "ADD_CART", payload: {...data, quantity: qty}});
            toast.success(`${data?.productName} added to the cart`);
            localStorage.setItem("cartItems", JSON.stringify(getState().carts.cart));
        } else {
            // error
            toast.error("Out of stock");
        }
};


export const increaseCartQuantity = 
    (data, toast, currentQuantity, setCurrentQuantity) =>
    (dispatch, getState) => {
        // Find the product
        const products = getState().products.products || [];
        
        const getProduct = products.find(
            (item) => item.productId === data.productId
        );

        const nextQuantity = Number(currentQuantity) + 1;
        const availableQuantity = getProduct?.quantity;
        const isQuantityExist = availableQuantity == null || Number(availableQuantity) >= nextQuantity;

        if (isQuantityExist) {
            setCurrentQuantity(nextQuantity);

            dispatch({
                type: "ADD_CART",
                payload: {...data, quantity: nextQuantity },
            });
            localStorage.setItem("cartItems", JSON.stringify(getState().carts.cart));
        } else {
            toast.error("Quantity Reached to Limit");
        }

    };



